// legacySymbol decodes an AppleScript 1.0 symbol payload.
func legacySymbol(data []byte) (fasCode, bool) {
	if len(data) != 4 {
		return fasCode{}, false
	}
	v := binary.BigEndian.Uint32(data)
	if v&7 != 1 {
		return fasCode{}, false
	}
	c, ok := legacySymbols[v>>3]
	return c, ok
}
