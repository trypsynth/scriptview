// genclassic writes scpt/classic.tsv: terminology from classic Mac
// OS scripting dictionaries (aete resources) that macOS no longer has, such
// as old scripting additions, PlainTalk's Speech Scripting, the Finder
// Scripting Extension and Scriptable Text Editor. scriptview uses these
// terms only for scripts from classic Mac OS.
//
// The dictionaries come from Apple's 1993 and 1994 discs, which the repository
// can't include. Extract each English (ID 0) aete resource to a file, list them
// newest first in a manifest of tab-separated lines
//
//	file	type	creator	size	name
//
// and run from the repo root:
//
//	go run ./tools/genclassic dir/manifest.tsv
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/trypsynth/scriptview/internal/aete"
)

// version matches a version number at the end of an application's file
// name: Finder Liaison 1.1, Progress Bar 1.0.1.
var version = regexp.MustCompile(` v?[0-9]+(\.[0-9]+)+$`)

// scopes returns the scopes a dictionary's terms belong to: "" for scripting
// additions, which every script sees, and the application's names otherwise.
func scopes(typ, creator, name string) []string {
	switch {
	case typ == "osax", typ == "INIT" && creator == "ears": // SR Monitor runs speech rules, which need no tell
		return []string{""}
	case typ == "fext" || typ == "FNDR": // Finder Scripting Extension, Finder
		return []string{"Finder"}
	case typ == "INIT" && strings.HasPrefix(name, "AppleScript"):
		return []string{"AppleScript"}
	case typ == "APPL":
		out := []string{name}
		if short := version.ReplaceAllString(name, ""); short != name {
			out = append(out, short)
		}
		if name == "HyperCard Player" {
			out = append(out, "HyperCard")
		}
		return out
	}
	return nil
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: genclassic manifest.tsv")
	}
	manifest := os.Args[1]
	f, err := os.Open(manifest)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	seen := map[string]bool{}
	var buf bytes.Buffer
	buf.WriteString("# Generated by tools/genclassic from classic Mac OS aete resources. DO NOT EDIT.\n")
	count := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Split(sc.Text(), "\t")
		if len(fields) < 5 {
			continue
		}
		file, typ, creator, name := fields[0], fields[1], fields[2], fields[4]
		data, err := os.ReadFile(filepath.Join(filepath.Dir(manifest), file))
		if err != nil {
			log.Fatal(err)
		}
		for _, scope := range scopes(typ, creator, name) {
			terms, err := aete.Parse(data, scope)
			if err != nil {
				log.Printf("skip %s: %v", name, err)
				break
			}
			for _, t := range terms {
				switch t.Kind {
				case "v", "a", "c", "p", "e", "E":
				default:
					continue // pipe-word hints are about AppleScript's own aeut
				}
				// The manifest lists the newest dictionaries first.
				key := t.Scope + "\x00" + t.Kind + "\x00" + t.Code
				if t.Code == "" || t.Name == "" || seen[key] {
					continue
				}
				seen[key] = true
				fmt.Fprintf(&buf, "%s\t%s\t%s\t%s", t.Scope, t.Kind, t.Code, t.Name)
				if t.Plural != "" {
					fmt.Fprintf(&buf, "\t%s", t.Plural)
				}
				buf.WriteByte('\n')
				count++
			}
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("scpt/classic.tsv", buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d terms\n", count)
}
